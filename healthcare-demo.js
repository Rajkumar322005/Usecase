  function handleAppointment(action, value) {
    if (action === 'appointment-for') {
      state.data.relationship = value;
      if (state.mode === 'text') state.data.specialty = 'cardiology';
      setStep(0);
      reply(tx('chooseHospital'), function () { locationCards('select-hospital'); });
    } else if (action === 'select-hospital') {
      state.data.hospital = LOCATIONS.find(function (item) { return item.id === value; });
      setStep(1);
      if (state.mode === 'text') {
        replySequence(tx('loadingDoctors'), tx('doctorsAtHospital'), function () { doctorCards('select-doctor', DOCTORS.cardiology, 'cardiology'); });
        return;
      }
      reply(tx('chooseSpecialty'), function () {
        choices(['cardiology','orthopaedics','dermatology','generalMedicine','paediatrics'].map(function (key) {
          return { label:tx(key), action:'select-specialty', value:key };
        }));
      });
    } else if (action === 'select-specialty') {
      state.data.specialty = value;
      setStep(1);
      replySequence(tx('loadingDoctors'), tx('doctorsFound'), function () { doctorCards('select-doctor', DOCTORS[value], value); });
    } else if (action === 'select-doctor') {
      state.data.doctor = DOCTORS[state.data.specialty].find(function (item) { return item.id === value; });
      setStep(2);
      reply(interpolate('doctorFeeVisit', { doctor:state.data.doctor.name, fee:state.data.doctor.fee }), function () { datePicker('appointment-date'); });
    } else if (action === 'appointment-date') {
      state.data.date = value;
      state.data.dateLabel = formatAppointmentDate(value);
      reply(tx('slotsAvailable'), function () { slotPicker('appointment-slot'); });
    } else if (action === 'appointment-slot') {
      state.data.slot = value;
      reply(tx('reserveSlot'), collectAppointmentDetails);
    } else if (action === 'patient-name') {
      state.data.patient = value;
      reply(tx('askPhone'), function () {
        choices([{ label:'9876543210', action:'patient-phone', value:'9876543210' }]);
      });
    } else if (action === 'patient-phone') {
      state.data.phone = value;
      showAppointmentReview();
    } else if (action === 'appointment-details') {
      try {
        const details = JSON.parse(value);
        state.data.patient = details.patient;
        state.data.phone = details.phone;
        showAppointmentReview();
      } catch (error) {
        state.awaiting = true;
      }
    } else if (action === 'appointment-summary-continue') {
      showPaymentChoice();
    } else if (action === 'payment-method' && value === 'pay-now') {
      showPaymentCard();
    } else if (action === 'payment-method' && value === 'hospital') {
      state.data.paymentStatus = tx('payAtHospital');
      reply(interpolate('payAtHospitalExplanation', { fee:state.data.doctor.fee }), function () {
        reply(tx('requestSubmittedMessage'), appointmentConfirmation);
      });
    } else if (action === 'payment-pay') {
      completeDemoPayment();
    } else if (action === 'appointment-reschedule') {
      setStep(2);
      reply(tx('chooseDate'), function () { datePicker('appointment-date'); });
    } else if (action === 'appointment-cancel') {
      reply(tx('confirmCancel'), function () {
        choices([
          { label:tx('yes'), action:'appointment-cancel-yes', value:'yes' },
          { label:tx('no'), action:'appointment-cancel-no', value:'no' }
        ]);
      });
    } else if (action === 'appointment-cancel-yes') {
      reply(tx('bookingCancelled'), function () {
        choices([{ label:tx('bookAnother'), action:'appointment-reschedule', value:'' },{ label:tx('close'), action:'close', value:'' }]);
      });
    } else if (action === 'appointment-cancel-no') {
      appointmentConfirmation();
    }
  }

