  function scheduleVirtualSelection(items) {
    const expected = expectedSelection();
    const item = items.find(function (candidate) { return matchesExpected(candidate, expected); });
    if (!item) return;
    const button = makeButton(item.label, item.action, item.value);
    button.dataset.label = autoTx(expected[2]) || item.label;
    const token = state.token;
    state.awaiting = true;
    later(function () {
      if (!state.awaiting || token !== state.token) return;
      state.demoIndex += 1;
      processAction(button);
    }, 980, token);
  }

  function scheduleAutoSelection(kind) {
    if (state.mode !== 'text') return;
    const expected = expectedSelection();
    if (!expected) return;
    const buttons = Array.from(chat.querySelectorAll('[data-action]')).filter(function (button) {
      return !button.disabled && button.dataset.action === expected[0] &&
        String(expected[1]) === String(button.dataset.value || '');
    });
    const button = buttons[buttons.length - 1];
    if (!button) return;
    button.dataset.label = autoTx(expected[2]) || button.dataset.label;
    const token = state.token;
    const dwell = kind === 'rich' ? 1500 : 850;
    later(function () {
      if (!state.awaiting || button.disabled) return;
      if (button.dataset.action === 'rate') {
        const rating = Number(button.dataset.value);
        button.closest('.rating-row').querySelectorAll('.star-btn').forEach(function (star, index) {
          if (index < rating) star.classList.add('demo-pick');
        });
      } else {
        button.classList.add('demo-pick');
      }
      const card = button.closest('.cc-card');
      if (card) card.classList.add('demo-selected');
      if (card && typeof card.scrollIntoView === 'function') card.scrollIntoView({ behavior:'smooth', block:'nearest', inline:'center' });
      state.demoIndex += 1;
      later(function () {
        if (state.awaiting && !button.disabled) button.click();
      }, 650, token);
    }, dwell, token);
  }

