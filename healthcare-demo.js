      const place = LOCATIONS.find(function (item) { return item.id === value; }) || state.data.hospital || LOCATIONS[0];
      reply(tx('call') + ': CarePlus demo helpline · +91 80 4000 2200', function () {
        if (state.flow === 0 && !state.data.hospital) choices([{ label:tx('selectHospital'), action:'select-hospital', value:place.id }]);
        else if (state.flow === 2 && !state.data.methodLabel) choices([{ label:tx('select'), action:'lab-centre', value:place.id }]);
        else if (state.flow === 4 && !state.data.fulfilment) choices([{ label:tx('select'), action:'pharmacy-branch', value:place.id }]);
        else choices([{ label:tx('done'), action:'done' }]);
      });
